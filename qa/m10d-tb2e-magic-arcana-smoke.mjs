import assert from "node:assert/strict";
import {tb2eMagicMemoryPlan as memory,tb2eMagicSpellbookPlan as book,
 tb2eMagicCastPlan as cast,tb2eMagicDischargePlan as discharge,
 tb2eMagicSpellInterruptPlan as interrupt} from "../module/m10d-tb2e-magic-arcana-shadow.mjs";
import {tb2eMagicModel,tb2eMagicShadowStatus} from "../module/m10d-tb2e-magic-shadow.mjs";
const safe=p=>{assert.equal(p.mode,"READ_ONLY_SHADOW");assert.equal(p.liveApplication,false);
 assert.equal(p.writesPlanned,0);assert.equal(p.actorWrite,false);
 assert.equal(p.itemWrite,false);assert.equal(p.spellWrite,false);
 assert.equal(p.rollExecuted,false);assert.equal(p.commitAllowed,false);};
const state=tb2eMagicShadowStatus();
assert.equal(state.adapterReady,true);assert.equal(state.liveApplication,false);
assert.equal(state.activationAllowed,false);assert.equal(state.sourceClassification,"VERIFIED");
const model=tb2eMagicModel();safe(model);
assert.equal(model.spellbookFolios,5);assert.equal(model.memorizationSkill,"Lore Master");
const args={capacity:5,currentSpells:[{id:"old",circle:1}],newSpells:[
 {id:"one",circle:1},{id:"two",circle:2}],carriedBookSpells:["one","two"]};
const camp=memory(args);safe(camp);assert.equal(camp.ok,true);
assert.equal(camp.obstacle,4);assert.equal(camp.currentSlots,1);
assert.equal(camp.newSlots,3);assert.equal(camp.remainingSlots,1);
assert.equal(camp.checksRequired,1);assert.equal(camp.memorizationCommitted,false);
assert.equal(memory({...args,capacity:3}).reasonCode,"MEMORY_PALACE_CAPACITY_EXCEEDED");
assert.equal(memory({...args,onWatch:true}).reasonCode,"CANNOT_MEMORIZE_WHILE_ON_WATCH");
assert.equal(memory({...args,phase:"ADVENTURE"}).ok,false);
assert.equal(memory({...args,carriedBookSpells:["one"]}).reasonCode,"SPELL_NOT_IN_CARRIED_SPELLBOOK");
assert.equal(memory({...args,phase:"TOWN",townAccommodation:true}).lifestyleCostDelta,0);
assert.equal(memory({...args,phase:"TOWN"}).lifestyleCostDelta,1);
assert.equal(book({existingSpells:[{circle:1}],newSpells:[{circle:3}]}).freeFolios,1);
assert.equal(book({existingSpells:[{circle:3}],newSpells:[{circle:3}]}).ok,false);
const castArgs={castingMode:"FIXED",source:"MEMORY",memorized:true,materials:true,focus:true};
const spell=cast(castArgs);safe(spell);assert.equal(spell.ok,true);
assert.equal(spell.materialBonusDice,1);assert.equal(spell.focusBonusDice,1);
assert.equal(spell.memorizedSpellReleasedPlanned,true);
assert.equal(spell.castCommitted,false);
assert.equal(cast({source:"MEMORY"}).ok,false);
assert.equal(cast({source:"SCROLL",hasScroll:true}).scrollConsumedPlanned,true);
assert.equal(cast({source:"SPELL_BOOK",inSpellBook:true}).spellbookSpellConsumedPlanned,true);
assert.equal(cast({...castArgs,canSpeak:false}).ok,false);
assert.equal(cast({...castArgs,freeHandToGesture:false}).ok,false);
assert.equal(cast({...castArgs,castingTurns:1,helpingArcanists:1}).turns,2);
assert.equal(cast({...castArgs,inConflict:true,conflictTiming:"BETWEEN_ROUNDS",castingTurns:1}).ok,false);
assert.equal(cast({...castArgs,inConflict:true,conflictTiming:"BETWEEN_ROUNDS",targetOpposition:true}).ok,false);
assert.equal(cast({...castArgs,inConflict:true,conflictTiming:"BETWEEN_ROUNDS",freeSpellsAlreadyThisRound:1}).ok,false);
assert.equal(cast({...castArgs,inConflict:true,conflictTiming:"BETWEEN_ROUNDS"}).ok,true);
assert.equal(cast({...castArgs,castingMode:"SKILL_SWAP",inConflict:true,conflictTiming:"ACTION",equippedThisRound:true}).ok,true);
assert.equal(cast({...castArgs,castingMode:"SKILL_SWAP",inConflict:true,conflictTiming:"ACTION"}).ok,false);
assert.equal(cast({...castArgs,castingMode:"SKILL_SWAP",inConflict:true,conflictTiming:"ACTION",equippedThisRound:true,helpingArcanists:1}).ok,false);
const d=discharge({memorySpells:[{circle:1},{circle:2}]});safe(d);
assert.equal(d.obstacle,3);assert.equal(d.turns,0);assert.equal(d.checksRequired,0);
const i=interrupt({memorySpells:[{circle:1},{circle:2}],helpers:1});safe(i);
assert.equal(i.willTestObstacle,3);assert.equal(i.willTestForCasterAndHelpers,2);
console.log("PASS M10D.18 P2.4 Arcana: memory, books, casting, scrolls, time, conflicts, interrupts; zero writes");
